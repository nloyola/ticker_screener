import datetime as _dt
import sqlite3
from collections.abc import Iterator
from contextlib import closing, contextmanager
from pathlib import Path

# Convert TIMESTAMP <-> datetime and DATE <-> date via ISO 8601, for every connection opened with
# detect_types=sqlite3.PARSE_DECLTYPES. Registered once here, at import, rather than per connection: every
# repository imports this module, so they all read and write dates the same way.
sqlite3.register_adapter(_dt.datetime, lambda dt: dt.isoformat(timespec='seconds'))
sqlite3.register_converter('TIMESTAMP', lambda b: _dt.datetime.fromisoformat(b.decode()))
sqlite3.register_adapter(_dt.date, lambda d: d.isoformat())
sqlite3.register_converter('DATE', lambda b: _dt.date.fromisoformat(b.decode()))

# How long a connection waits for a lock held by another connection before
# raising "database is locked". The stock_analyzer dashboard reads this file
# while a screener run writes it; schema.sql puts it in WAL mode, where readers
# never block the writer, but two writers still queue for the write lock.
BUSY_TIMEOUT_MS = 30_000


def open_connection(db_path: str, **kwargs) -> sqlite3.Connection:
    """Opens a connection to the database. Every connection must come from here."""
    con = sqlite3.connect(db_path, **kwargs)
    con.execute(f'PRAGMA busy_timeout = {BUSY_TIMEOUT_MS}')
    return con


@contextmanager
def connect(db_path: str) -> Iterator[sqlite3.Connection]:
    """Opens a repository's connection, with the type converters, sqlite3.Row rows and foreign keys on.

    Commits on success, rolls back on an exception, and closes the connection either way: a bare `with con:` only
    commits or rolls back, and leaves the connection open.
    """
    con = open_connection(db_path, detect_types=sqlite3.PARSE_DECLTYPES)
    with closing(con):
        con.row_factory = sqlite3.Row
        con.execute('PRAGMA foreign_keys = ON')  # SQLite turns foreign keys on per connection, outside a transaction
        with con:
            yield con


class SQLite:
    def __init__(self, db_path: str):
        self.db_path = db_path

    @contextmanager
    def connect(self) -> Iterator[sqlite3.Connection]:
        con = open_connection(
            self.db_path,
            detect_types=sqlite3.PARSE_DECLTYPES,  # use TIMESTAMP converter
            isolation_level=None,  # autocommit mode; we'll BEGIN manually
        )
        con.row_factory = sqlite3.Row
        try:
            con.execute('PRAGMA foreign_keys = ON')  # as connect() does; it has no effect inside a transaction
            con.execute('BEGIN')
            yield con
            con.execute('COMMIT')
        except BaseException:  # KeyboardInterrupt and SystemExit too: never leave a transaction open
            con.execute('ROLLBACK')
            raise
        finally:
            con.close()


# Tables filled by the screener's market data runs. Their rows point at
# subsector ids and are regenerated by the next run, so they can be emptied
# freely. Every other table (sector, subsector, and tables owned by other
# programs sharing this database) must be left alone.
MARKET_DATA_TABLES = ('ticker', 'price_data', 'stock_criteria', 'metadata')


def clear_market_data(con: sqlite3.Connection) -> None:
    for table in MARKET_DATA_TABLES:
        con.execute(f'DELETE FROM {table}')


# schema.sql sits at the repo root, beside app/: found from this file, so commands run from any directory
SCHEMA_FILE = Path(__file__).resolve().parent.parent / 'schema.sql'


def init_db(db_path: str):
    schema = SCHEMA_FILE.read_text(encoding='utf-8')
    con = open_connection(db_path)
    try:
        con.executescript(schema)
    finally:
        con.close()
