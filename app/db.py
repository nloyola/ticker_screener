import datetime as _dt
import logging
import sqlite3
from collections.abc import Iterator
from contextlib import closing, contextmanager
from pathlib import Path

logger = logging.getLogger(__name__)

# Convert TIMESTAMP <-> datetime and DATE <-> date via ISO 8601, for every connection opened with
# detect_types=sqlite3.PARSE_DECLTYPES. Registered once here, at import, rather than per connection: every
# repository imports this module, so they all read and write dates the same way.
sqlite3.register_adapter(_dt.datetime, lambda dt: dt.isoformat(timespec='seconds'))
sqlite3.register_converter('TIMESTAMP', lambda b: _dt.datetime.fromisoformat(b.decode()))
sqlite3.register_adapter(_dt.date, lambda d: d.isoformat())
sqlite3.register_converter('DATE', lambda b: _dt.date.fromisoformat(b.decode()))

# How long a connection waits for a lock held by another connection before
# raising "database is locked". The stock_analyzer dashboard reads this file
# while a screener run writes it; schema.sql puts it in WAL mode, where readers
# never block the writer, but two writers still queue for the write lock.
BUSY_TIMEOUT_MS = 30_000


def open_connection(db_path: str, **kwargs) -> sqlite3.Connection:
    """Opens a connection to the database. Every connection must come from here."""
    con = sqlite3.connect(db_path, **kwargs)
    con.execute(f'PRAGMA busy_timeout = {BUSY_TIMEOUT_MS}')
    return con


@contextmanager
def connect(db_path: str) -> Iterator[sqlite3.Connection]:
    """Opens a repository's connection, with the type converters, sqlite3.Row rows and foreign keys on.

    Commits on success, rolls back on an exception, and closes the connection either way: a bare `with con:` only
    commits or rolls back, and leaves the connection open.
    """
    con = open_connection(db_path, detect_types=sqlite3.PARSE_DECLTYPES)
    with closing(con):
        con.row_factory = sqlite3.Row
        con.execute('PRAGMA foreign_keys = ON')  # SQLite turns foreign keys on per connection, outside a transaction
        with con:
            yield con


class SQLite:
    def __init__(self, db_path: str):
        self.db_path = db_path

    @contextmanager
    def connect(self) -> Iterator[sqlite3.Connection]:
        con = open_connection(
            self.db_path,
            detect_types=sqlite3.PARSE_DECLTYPES,  # use TIMESTAMP converter
            isolation_level=None,  # autocommit mode; we'll BEGIN manually
        )
        con.row_factory = sqlite3.Row
        try:
            con.execute('PRAGMA foreign_keys = ON')  # as connect() does; it has no effect inside a transaction
            con.execute('BEGIN')
            yield con
            con.execute('COMMIT')
        except BaseException:  # KeyboardInterrupt and SystemExit too: never leave a transaction open
            if con.in_transaction:  # SQLite may have rolled it back already, and ROLLBACK would hide the error
                con.execute('ROLLBACK')
            raise
        finally:
            con.close()


# Tables filled by the screener's market data runs. Their rows point at
# subsector ids and are regenerated by the next run, so they can be emptied
# freely. Every other table (sector, subsector, and tables owned by other
# programs sharing this database) must be left alone.
MARKET_DATA_TABLES = ('ticker', 'price_data', 'stock_criteria', 'metadata')


def clear_market_data(con: sqlite3.Connection) -> None:
    for table in MARKET_DATA_TABLES:
        con.execute(f'DELETE FROM {table}')


# schema.sql sits at the repo root, beside app/: found from this file, so commands run from any directory
SCHEMA_FILE = Path(__file__).resolve().parent.parent / 'schema.sql'


def init_db(db_path: str):
    """Brings the database up to the current schema: upgrades the tables it already has, then creates the rest."""
    upgrade_db(db_path)
    schema = SCHEMA_FILE.read_text(encoding='utf-8')
    con = open_connection(db_path)
    try:
        con.executescript(schema)
        # every table now matches schema.sql: the upgrade fixed the old ones, the script created the missing ones
        con.execute(f'PRAGMA user_version = {SCHEMA_VERSION}')
    finally:
        con.close()


# Upgrades for databases created by an older schema.sql, which only creates missing tables and so never changes
# one that exists. UPGRADES[n] takes a database from version n to n + 1, recorded in PRAGMA user_version; the
# dashboard keeps its own migrations in its own table and never reads or writes user_version. To change an
# existing table, change schema.sql and append an upgrade that leaves an old table exactly as schema.sql now
# creates it. Never edit an upgrade that has shipped.


def _guard_price_data_date(con: sqlite3.Connection) -> None:
    """Version 1: price_data.date is NOT NULL and a real YYYY-MM-DD date.

    SQLite cannot add a constraint to a column, so the table is rebuilt: every row is copied with its id, and the
    AUTOINCREMENT sequence is kept, so ids deleted rows used are never reused. A row the new CHECK refuses fails
    the whole upgrade rather than being dropped.
    """
    if not con.execute("SELECT 1 FROM sqlite_master WHERE type = 'table' AND name = 'price_data'").fetchone():
        return  # schema.sql creates it with the guard
    seq = con.execute("SELECT seq FROM sqlite_sequence WHERE name = 'price_data'").fetchone()
    con.execute("""
        CREATE TABLE price_data_new (
               id INTEGER PRIMARY KEY AUTOINCREMENT,
               subsector_id INTEGER,
               ticker TEXT,
               date TEXT NOT NULL CHECK (date(date) IS date),
               close REAL,
               volume INTEGER,
               UNIQUE (ticker, date)
        )""")
    # the column list is spelled out here, not shared, so that a later schema change cannot alter a shipped upgrade
    rows = con.execute(
        'INSERT INTO price_data_new (id, subsector_id, ticker, date, close, volume) '
        'SELECT id, subsector_id, ticker, date, close, volume FROM price_data'
    ).rowcount
    con.execute('DROP TABLE price_data')
    con.execute('ALTER TABLE price_data_new RENAME TO price_data')
    if seq is not None:
        # the copy set the sequence to the highest id copied, which is below the old one if the top rows were deleted
        con.execute("UPDATE sqlite_sequence SET seq = max(seq, ?) WHERE name = 'price_data'", (seq[0],))
        con.execute(
            "INSERT INTO sqlite_sequence (name, seq) SELECT 'price_data', ? "
            "WHERE NOT EXISTS (SELECT 1 FROM sqlite_sequence WHERE name = 'price_data')",
            (seq[0],),
        )
    logger.info('Rebuilt price_data with the date guard, keeping its %d rows', rows)


def _add_company_name(con: sqlite3.Connection) -> None:
    """Version 2: the company_name table, which schema.sql only creates when db-init runs."""
    # spelled out here, not read from schema.sql, so that a later schema change cannot alter a shipped upgrade
    con.execute("""
        CREATE TABLE IF NOT EXISTS company_name (
               ticker TEXT NOT NULL PRIMARY KEY COLLATE NOCASE,
               name TEXT NOT NULL,
               price_api TEXT NOT NULL CHECK (price_api IN ('tiingo', 'eodhd')),
               stored_at TIMESTAMP NOT NULL DEFAULT (datetime('now'))
        )""")


def _add_price_data_high_low(con: sqlite3.Connection) -> None:
    """
    Version 3: price_data.high and price_data.low, left NULL in the rows already stored. Adds only a column the table
    lacks, so a table schema.sql created with them is left as it is.
    """
    columns = {row[1] for row in con.execute("PRAGMA table_info('price_data')")}
    if not columns:
        return  # no table: schema.sql creates it with both columns
    for column in ('high', 'low'):
        if column not in columns:
            con.execute(f'ALTER TABLE price_data ADD COLUMN {column} REAL')


UPGRADES = (_guard_price_data_date, _add_company_name, _add_price_data_high_low)
SCHEMA_VERSION = len(UPGRADES)


def _user_version(con: sqlite3.Connection) -> int:
    return con.execute('PRAGMA user_version').fetchone()[0]


def upgrade_db(db_path: str) -> None:
    """Applies the upgrades a database has not had yet, all in one transaction. A missing file is left alone.

    Every command runs this before it opens the database, so the first one after a release upgrades it. Two
    commands starting together queue for the write lock, and the second finds the work done.
    """
    if not Path(db_path).exists():
        return
    con = open_connection(db_path, isolation_level=None)  # autocommit mode; we BEGIN and COMMIT ourselves
    try:
        if _user_version(con) == SCHEMA_VERSION:
            return  # the usual case, checked without taking the write lock
        con.execute('BEGIN IMMEDIATE')
        try:
            version = _user_version(con)  # again under the lock: another command may have just upgraded it
            if version > SCHEMA_VERSION:
                raise RuntimeError(
                    f'{db_path} is at schema version {version}, newer than this screener knows ({SCHEMA_VERSION})'
                )
            for upgrade in UPGRADES[version:]:
                upgrade(con)
            con.execute(f'PRAGMA user_version = {SCHEMA_VERSION}')
            con.execute('COMMIT')
        except BaseException:  # as SQLite.connect does: never leave a transaction open
            if con.in_transaction:  # SQLite may have rolled it back already, and ROLLBACK would hide the error
                con.execute('ROLLBACK')
            raise
        logger.info('Upgraded %s from schema version %d to %d', db_path, version, SCHEMA_VERSION)
    finally:
        con.close()
